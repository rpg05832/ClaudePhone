import { test } from 'node:test';
import assert from 'node:assert/strict';
import { normalizeSpelled as n } from '../src/stt/normalize.ts';

test('כתובת מייל מאויתת: אותיות, מספר במילים, שטרודל, ג\'ימייל נקודה קום', () => {
  assert.equal(n('תשלח ל איי בי אלף מאתיים שלושים וארבע שטרודל ג\'ימייל נקודה קום את הדוח'), 'תשלח ל AB1234@gmail.com את הדוח');
  assert.equal(n('איי בי 1234 שטרודל גימייל נקודה קום.'), 'AB1234@gmail.com.');
  assert.equal(n('A B 1,234 שטרודל ג׳י מייל דוט קום'), 'AB1234@gmail.com');
  // חלק מקומי בעברית לא מומר (אין איות), הדומיין כן
  assert.equal(n('יעקב כהן שטרודל וואלה נקודה קו איל'), 'יעקב כהן @walla.co.il');
  assert.equal(n('אפס חמש אפס אחת שתיים שלוש ארבע חמש שש שבע'), '0501234567');
});

test('מספרים במילים בתוך איות', () => {
  assert.equal(n('אס אם אחת עשרה שטרודל הוטמייל נקודה קום'), 'SM11@hotmail.com');
  assert.equal(n('די אי אלפיים ועשרים שטרודל יאהו נקודה קום'), 'DE2020@yahoo.com');
  assert.equal(n('אם אי שלושת אלפים שטרודל ג\'ימייל נקודה קום'), 'ME3000@gmail.com');
});

test('קו תחתון, מקף ו-www', () => {
  assert.equal(n('ג\'יי קו תחתון סי מקף אחת שטרודל ג\'ימייל נקודה קום'), 'J_C-1@gmail.com');
  assert.equal(n('תיכנס ל דאבליו דאבליו דאבליו נקודה גוגל נקודה קום ותבדוק'), 'תיכנס ל www.google.com ותבדוק');
  assert.equal(n('האתר הוא בזק נקודה נט'), 'האתר הוא בזק.net');
});

test('איות בלי כתובת: שתי אותיות ומעלה', () => {
  assert.equal(n('תמיר את הקובץ ל פי די אף בבקשה'), 'תמיר את הקובץ ל PDF בבקשה');
  assert.equal(n('הקוד הוא איי בי סי אחת שתיים שלוש'), 'הקוד הוא ABC123');
});

test('עברית רגילה לא נפגעת', () => {
  for (const s of ['אי אפשר לעשות את זה', 'די, זה מספיק', 'אם אין קובץ תיצור אחד', 'או שנחכה', 'תוסיף נקודה חשובה בסוף', 'תן לי שלוש אפשרויות', 'הדוח של שבעים עובדים', 'בוא נלך אל הבית']) {
    assert.equal(n(s), s);
  }
  assert.equal(n(''), '');
});
